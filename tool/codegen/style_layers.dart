// Generates the typed style layers of maplibre_platform_interface from the
// MapLibre style spec. Run it after raising the spec version:
//
//   cd tool/codegen && dart run style_layers.dart [path/to/v8.json]
//
// Without a path it downloads v8.json of the version below from npm's CDN.

import 'dart:convert';
import 'dart:io';

/// The version of the npm package @maplibre/maplibre-gl-style-spec.
const _specVersion = '26.5.0';

const _specUrl =
    'https://unpkg.com/@maplibre/maplibre-gl-style-spec@$_specVersion/'
    'src/reference/v8.json';

const _docsUrl = 'https://maplibre.org/maplibre-style-spec';

/// The layer types in the order of the generated file.
const _layerTypes = [
  'background',
  'circle',
  'color-relief',
  'fill',
  'fill-extrusion',
  'heatmap',
  'hillshade',
  'line',
  'raster',
  'symbol',
];

Future<void> main(List<String> args) async {
  final spec = jsonDecode(
    args.isEmpty
        ? await _download(Uri.parse(_specUrl))
        : File(args.single).readAsStringSync(),
  ) as Map<String, Object?>;
  final package = Platform.script.resolve(
    '../../packages/maplibre_platform_interface/lib/src/style/',
  );
  final outputs = {
    package.resolve('layers/style_layers.g.dart'): _Generator(spec).generate(),
    package.resolve('expressions/spec_operators.g.dart'): _operators(spec),
  };
  for (final MapEntry(:key, :value) in outputs.entries) {
    File.fromUri(key).writeAsStringSync(value);
  }
  final format = Process.runSync(Platform.resolvedExecutable, [
    'format',
    for (final uri in outputs.keys) uri.toFilePath(),
  ]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
}

Future<String> _download(Uri url) async {
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(url)).close();
    if (response.statusCode != 200) {
      throw HttpException('HTTP ${response.statusCode}', uri: url);
    }
    return await utf8.decodeStream(response);
  } finally {
    client.close();
  }
}

String _operators(Map<String, Object?> spec) {
  final expressionName = spec['expression_name']! as Map<String, Object?>;
  final names = (expressionName['values']! as Map<String, Object?>).keys;
  return '''
// GENERATED by tool/codegen/style_layers.dart from the style spec $_specVersion.
// Do not edit by hand.

/// The operators of style expressions, and those only legacy filters have.
const specExpressionOperators = <String>{
  ${names.map((name) => "'$name',").join('\n  ')}
  '!in',
  '!has',
  'none',
};
''';
}

/// The Dart side of a property's spec type.
class _DartType {
  const _DartType(this.name, this.decoder, this.defaultOf);

  /// The `T` of its `Expression<T>`.
  final String name;

  /// A Dart expression of the `LiteralDecoder<T>`.
  final String decoder;

  /// The const Dart expression of a default value in the spec.
  final String Function(Object? value) defaultOf;
}

class _Generator {
  _Generator(this.spec);

  final Map<String, Object?> spec;

  /// The generated enums by name, to their spec values.
  final _enums = <String, List<String>>{};
  final _enumCode = StringBuffer();

  Map<String, Object?> _group(String name) =>
      (spec[name] as Map<String, Object?>?) ?? const {};

  String generate() {
    final classes = StringBuffer();
    for (final type in _layerTypes) {
      _generateClass(type, classes);
    }
    final fromJson = _layerTypes
        .map((type) => "'$type' => ${_className(type)}.fromJson(json),")
        .join('\n    ');
    return '''
// GENERATED by tool/codegen/style_layers.dart from the style spec $_specVersion.
// Do not edit by hand.

part of 'style_layer.dart';

StyleLayer _layerFromJson(Map<String, Object?> json) =>
    switch (json['type']) {
    $fromJson
    _ => UnknownStyleLayer.fromJson(json),
    };

$classes
$_enumCode
''';
  }

  void _generateClass(String type, StringBuffer out) {
    final layout = _group('layout_$type');
    final paint = _group('paint_$type');
    final properties = {...layout, ...paint}..remove('visibility');
    final names = _dartNames(type, properties.keys);
    final hasSource = type != 'background';
    final className = _className(type);
    final layerTypes =
        ((spec['layer']! as Map<String, Object?>)['type']!
                as Map<String, Object?>)['values']!
            as Map<String, Object?>;
    final typeSpec = layerTypes[type]! as Map<String, Object?>;

    out
      ..writeln(_docComment(typeSpec['doc']! as String))
      ..writeln('///')
      ..writeln('/// $_docsUrl/layers/#$type')
      ..writeln('///')
      ..writeln('/// {@category Style}')
      ..writeln('/// {@subCategory Style Layers}')
      ..writeln(
        'final class $className extends '
        '${hasSource ? 'StyleLayerWithSource' : 'StyleLayer'} {',
      )
      ..writeln('/// Creates a [$className] that is not on a map yet.')
      ..writeln('$className({')
      ..writeln('required super.id,');
    if (hasSource) {
      out
        ..writeln('required super.sourceId,')
        ..writeln('super.sourceLayerId,');
    }
    out.writeln(
      'super.minZoom, super.maxZoom, super.filter, super.visible, '
      'super.layout, super.paint,',
    );

    final types = <String, _DartType>{};
    for (final MapEntry(:key, :value) in properties.entries) {
      final dartType = _typeOf(type, key, value! as Map<String, Object?>);
      types[key] = dartType;
      out.writeln('Expression<${dartType.name}>? ${names[key]},');
    }
    out.write('})');
    if (properties.isEmpty) {
      out.writeln(';');
    } else {
      out.writeln(' {');
      for (final key in properties.keys) {
        out.writeln("_initProperty('$key', ${names[key]});");
      }
      out.writeln('}');
    }
    out
      ..writeln()
      ..writeln('/// Reads a [$className] from the JSON of a style layer.')
      ..writeln(
        '$className.fromJson(Map<String, Object?> json) : '
        'super._fromJson(json);',
      )
      ..writeln()
      ..writeln('@override')
      ..writeln("String get type => '$type';")
      ..writeln()
      ..writeln('@override')
      ..writeln('Set<String> get _layoutProperties => const {')
      ..writeln(layout.keys.map((key) => "'$key',").join(' '))
      ..writeln('};');

    for (final MapEntry(:key, :value) in properties.entries) {
      final property = value! as Map<String, Object?>;
      final dartType = types[key]!;
      final name = names[key]!;
      final defaultValue = property['default'];
      out
        ..writeln()
        ..writeln(_propertyDoc(property));
      if (defaultValue == null) {
        out.writeln(
          'Expression<${dartType.name}>? get $name => '
          "_propertyOrNull('$key', ${dartType.decoder});",
        );
      } else {
        out.writeln(
          'Expression<${dartType.name}> get $name => '
          "_property('$key', ${dartType.decoder}, "
          // The default of heatmap-color is an expression.
          '${dartType == _color && defaultValue is List ? 'const Call(${jsonEncode(defaultValue)})' : 'const Literal(${dartType.defaultOf(defaultValue)})'});',
        );
      }
      out
        ..writeln()
        ..writeln(
          'set $name(Expression<${dartType.name}>? value) => '
          "_setExpression('$key', value);",
        );
    }
    out.writeln('}\n');
  }

  /// The Dart names of [properties]: without the prefix of the layer type,
  /// unless that collides with another property of the layer.
  Map<String, String> _dartNames(String type, Iterable<String> properties) {
    final stripped = {
      for (final property in properties)
        property: property.startsWith('$type-')
            ? property.substring(type.length + 1)
            : property,
    };
    return {
      for (final MapEntry(:key, :value) in stripped.entries)
        key: _camelCase(
          stripped.values.where((name) => name == value).length > 1 &&
                  key != value
              ? key
              : value,
        ),
    };
  }

  _DartType _typeOf(
    String layerType,
    String property,
    Map<String, Object?> spec,
  ) {
    final type = spec['type']! as String;
    switch (type) {
      case 'number':
        return _number;
      case 'string' || 'resolvedImage' || 'formatted':
        return _string;
      case 'boolean':
        return _DartType('bool', 'decodeBool', (value) => '$value');
      case 'color':
        return _color;
      case 'enum':
        final name = _enumOf(layerType, property, spec);
        return _DartType(
          name,
          'decodeEnum($name.values)',
          (value) => '$name.${_enumMember(value! as String)}',
        );
      case 'array':
        final item = spec['value']! as String;
        switch (item) {
          case 'number' when spec['length'] == 2:
            return _DartType('Offset', 'decodeOffset', (value) {
              final [x, y] = value! as List<Object?>;
              return 'Offset($x, $y)';
            });
          case 'number':
            return _numList;
          case 'string':
            return _DartType(
              'List<String>',
              'decodeStringList',
              (value) => '<String>${_stringList(value)}',
            );
          case 'enum':
            final name = _enumOf(layerType, property, spec);
            return _DartType(
              'List<$name>',
              'decodeEnumList($name.values)',
              (value) =>
                  '<$name>[${(value! as List<Object?>).map((e) => '$name.${_enumMember(e! as String)}').join(', ')}]',
            );
        }
        throw UnsupportedError('An array of $item: $property');
      case 'padding' || 'numberArray':
        return _numList;
      case 'colorArray':
        return _DartType(
          'List<Color>',
          'decodeColorList',
          (value) => '<Color>[${_colorOf(value! as String)}]',
        );
      case 'variableAnchorOffsetCollection':
        return _DartType(
          'List<Object?>',
          'decodeObjectList',
          (value) => throw UnsupportedError('A default of $property'),
        );
    }
    throw UnsupportedError('The type $type of $property');
  }

  static final _number = _DartType('num', 'decodeNum', (value) => '$value');
  static final _string = _DartType(
    'String',
    'decodeString',
    (value) => jsonEncode(value).replaceAll(r'$', r'\$'),
  );
  static final _color = _DartType(
    'Color',
    'decodeColor',
    (value) => _colorOf(value! as String),
  );
  static final _numList = _DartType(
    'List<num>',
    'decodeNumList',
    (value) => value is List ? '<num>$value' : '<num>[$value]',
  );

  static String _stringList(Object? value) =>
      '[${(value! as List<Object?>).map(jsonEncode).join(', ')}]';

  /// The name of the enum of [property], which is generated on first use.
  /// A property without the prefix of its layer type gets it, and properties
  /// with the same values and name share the enum.
  String _enumOf(String layerType, String property, Map<String, Object?> spec) {
    final name = _pascalCase(
      property.contains('-') ? property : '$layerType-$property',
    );
    final values = spec['values']! as Map<String, Object?>;
    final existing = _enums[name];
    if (existing != null) {
      if (existing.join() != values.keys.join()) {
        throw StateError('Two enums named $name');
      }
      return name;
    }
    _enums[name] = values.keys.toList();
    _enumCode
      ..writeln(_docComment(spec['doc']! as String))
      ..writeln('///')
      ..writeln('/// {@category Style}')
      ..writeln('/// {@subCategory Style Layers}')
      ..writeln('enum $name implements StyleEnum {');
    for (final MapEntry(:key, :value) in values.entries) {
      final doc = (value! as Map<String, Object?>)['doc'] as String?;
      if (doc != null) _enumCode.writeln(_docComment(doc));
      _enumCode.writeln("${_enumMember(key)}('$key'),");
    }
    _enumCode
      ..writeln(';')
      ..writeln()
      ..writeln('const $name(this.value);')
      ..writeln()
      ..writeln('@override')
      ..writeln('final String value;')
      ..writeln('}')
      ..writeln();
    return name;
  }

  String _propertyDoc(Map<String, Object?> property) {
    final type = property['type'];
    final minimum = property['minimum'];
    final maximum = property['maximum'];
    final units = property['units'];
    final defaultValue = property['default'];
    return _docComment(
      [
        property['doc']! as String,
        if (units != null) 'In $units.',
        if (minimum != null || maximum != null)
          'Between ${minimum ?? '-∞'} and ${maximum ?? '∞'}.',
        if (defaultValue != null)
          'Defaults to `${type == 'string' ? defaultValue : jsonEncode(defaultValue)}`.',
        if (property['expression'] == null)
          'Takes no expressions, only literals.',
      ].join('\n\n'),
    );
  }

  static String _className(String type) => '${_pascalCase(type)}StyleLayer';

  static String _camelCase(String kebab) {
    final pascal = _pascalCase(kebab);
    return pascal[0].toLowerCase() + pascal.substring(1);
  }

  static String _pascalCase(String kebab) => kebab
      .split('-')
      .map((part) => part[0].toUpperCase() + part.substring(1))
      .join();

  static const _reserved = {'default', 'switch', 'class', 'in', 'is'};

  static String _enumMember(String value) {
    final name = _camelCase(value);
    return _reserved.contains(name) ? '${name}Value' : name;
  }

  /// A hex or `rgba()` color of the spec as a Dart const.
  static String _colorOf(String css) {
    if (RegExp(r'^#[0-9a-fA-F]{6}$').hasMatch(css)) {
      return 'Color(0xFF${css.substring(1).toUpperCase()})';
    }
    if (RegExp(r'^#[0-9a-fA-F]{3}$').hasMatch(css)) {
      final [r, g, b] = css.substring(1).toUpperCase().split('');
      return 'Color(0xFF$r$r$g$g$b$b)';
    }
    if (css == 'rgba(0, 0, 0, 0)') return 'Color(0x00000000)';
    throw UnsupportedError('The color $css');
  }

  /// [doc] as a doc comment, wrapped at 80 columns. Links between the pages of
  /// the spec become absolute.
  static String _docComment(String doc) {
    final text = doc
        .replaceAllMapped(
          RegExp(r'\]\((layers|expressions|sources|root|types)(/[^)]*)?\)'),
          (match) => ']($_docsUrl/${match[1]}${match[2] ?? ''})',
        )
        .replaceAllMapped(
          RegExp(r'\]\(#([^)]*)\)'),
          (match) => ']($_docsUrl/expressions/#${match[1]})',
        );
    final lines = <String>[];
    var inCode = false;
    for (final raw in text.split('\n')) {
      final line = raw.trim();
      if (line.startsWith('```')) inCode = !inCode;
      if (inCode || line.startsWith('```') || line.length <= 76) {
        lines.add(line);
        continue;
      }
      var current = '';
      for (final word in line.split(' ')) {
        if (current.isNotEmpty && current.length + word.length + 1 > 76) {
          lines.add(current);
          current = word;
        } else {
          current = current.isEmpty ? word : '$current $word';
        }
      }
      lines.add(current);
    }
    while (lines.isNotEmpty && lines.last.isEmpty) {
      lines.removeLast();
    }
    return lines.map((line) => '/// $line'.trimRight()).join('\n');
  }
}
